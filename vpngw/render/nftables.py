def render_killswitch(settings: Settings) -> str:
    """The ruleset loaded before the network comes up.

    Ordered ``Before=network-pre.target`` by its systemd unit, so between the
    kernel bringing interfaces up and vpngw finishing its first reconcile, the
    box is already refusing to forward. There is no permissive window at boot,
    which is the one hole most hand-rolled kill switches leave open.
    """
    net = settings.net

    # The skeleton has to keep the same administrative door open that the full
    # ruleset does. If it did not, a boot where vpngw fails to start would be
    # unreachable - fail-closed for clients is correct, but locking the
    # operator out of a box that needs fixing is just a brick.
    admin_rules = []
    for iface in net.management_ifaces():
        admin_rules.append(
            f'        iifname "{iface}" tcp dport {{ 22 }} accept'
        )
    admin_block = "\n".join(admin_rules) or (
        "        # no management path configured - see [net] in vpngw.toml"
    )

    return f"""\
#!/usr/sbin/nft -f
#
# vpngw boot-time fail-closed skeleton.
#
# Loaded before network-pre.target. If vpngw never starts - unit masked,
# database corrupt, Python broken by a bad upgrade - the box stays in this
# state and forwards nothing. Failure of the control plane is not a leak.

table inet vpngw
delete table inet vpngw

table inet vpngw {{
    counter wan_leak_drop     {{ comment "boot skeleton: uplink" }}
    counter nontunnel_drop    {{ comment "boot skeleton: non-tunnel" }}
    counter unclassified_drop {{ comment "boot skeleton: unclassified" }}

    chain forward {{
        type filter hook forward priority filter; policy drop;
        oifname "{net.wan_iface}" counter name "wan_leak_drop" drop
        counter name "unclassified_drop" drop
    }}

    chain input {{
        type filter hook input priority filter; policy drop;
        iif lo accept
        ct state established,related accept
{admin_block}
        icmp type echo-request accept
    }}

    chain output {{
        type filter hook output priority filter; policy accept;
    }}
}}
"""
